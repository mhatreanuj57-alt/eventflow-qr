import assert from 'node:assert/strict';
import { eventState, HIDE_DELAY, indiaTime, validateEvent, brandInk, addPreviewAttendee, checkPreviewPass, clearLocalTestData } from './src/platform-rules.js';
const event = { start: indiaTime('2026-10-05T10:00'), end: indiaTime('2026-10-05T17:00'), registrationOpen: indiaTime('2026-10-02T10:00'), registrationClose: indiaTime('2026-10-04T10:00') };
const open = Date.parse(event.registrationOpen), close = Date.parse(event.registrationClose);
assert.equal(new Date(open).toISOString(), '2026-10-02T04:30:00.000Z');
assert.equal(eventState(event, open - 1), 'scheduled');
assert.equal(eventState(event, open), 'open');
assert.equal(eventState(event, close - 1), 'open');
assert.equal(eventState(event, close), 'closed');
assert.equal(eventState(event, close + HIDE_DELAY - 1), 'closed');
assert.equal(eventState(event, close + HIDE_DELAY), 'hidden');
assert.equal(validateEvent(event), '');
assert.ok(validateEvent({ ...event, end: event.start }));
assert.ok(validateEvent({ ...event, registrationClose: event.registrationOpen }));
assert.ok(validateEvent({ ...event, start: 'invalid' }));
assert.ok(validateEvent({ ...event, registrationClose: indiaTime('2026-10-06T18:00') }));
assert.equal(brandInk('#000000'), '#ffffff');
assert.equal(brandInk('#ffffff'), '#000000');
assert.equal(brandInk('#ff5100'), '#000000');
const people = [], firstEvent = { ...event, id: 'one' }, secondEvent = { ...event, id: 'two' };
addPreviewAttendee(people, firstEvent, { id: 'EF-PREVIEW-ONE', token: 'opaque-one', email: ' GUEST@example.test ', name: 'Guest' }, open);
assert.throws(() => addPreviewAttendee(people, firstEvent, { email: 'guest@example.test' }, open), /Already registered/);
addPreviewAttendee(people, secondEvent, { id: 'EF-PREVIEW-TWO', token: 'opaque-two', email: 'guest@example.test' }, open);
assert.throws(() => addPreviewAttendee(people, firstEvent, { email: 'another@example.test' }, close), /not open/);
assert.deepEqual(checkPreviewPass(people, 'two', 'opaque-one'), { status: 'wrong_event' });
assert.equal(people[0].checkedInAt, undefined);
assert.deepEqual(checkPreviewPass(people, 'one', 'fake'), { status: 'invalid_pass' });
assert.equal(checkPreviewPass(people, 'one', 'opaque-one', '2026-10-05T04:30:00Z').status, 'checked_in');
const duplicate = checkPreviewPass(people, 'one', 'ef-preview-one', '2026-10-05T05:00:00Z');
assert.equal(duplicate.status, 'already_checked_in');
assert.equal(duplicate.attendee.checkedInAt, '2026-10-05T04:30:00Z');
assert.equal(people.filter(p => p.checkedInAt).length, 1);
console.log('PASS: scheduling boundaries, contrast, event-scoped registration, wrong-event/invalid passes, duplicate check-in and preserved timestamp.');
const stored = new Map([['eventflow-platform-design-v1', JSON.stringify([{ name: 'Fake one', logo: 'private-test-logo' }, { name: 'Fake two', owner: 'fictional@example.test' }])], ['unrelated', 'keep']]);
const storage = { getItem: key => stored.get(key), setItem: (key, value) => stored.set(key, value), removeItem: key => stored.delete(key) };
assert.equal(clearLocalTestData(storage), true);
assert.equal(stored.has('eventflow-platform-design-v1'), false);
assert.equal(stored.get('unrelated'), 'keep');
stored.set('eventflow-platform-design-v1', 'new-event');
assert.equal(clearLocalTestData(storage), false);
assert.equal(stored.get('eventflow-platform-design-v1'), 'new-event');
console.log('PASS: complete one-time local cleanup preserves unrelated storage and new events on later reloads.');
